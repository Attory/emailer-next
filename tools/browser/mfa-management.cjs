const fs = require('node:fs');
const crypto = require('node:crypto');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.EMAILER_PLAYWRIGHT_MODULE || 'playwright-core');
const config = JSON.parse(fs.readFileSync(process.env.EMAILER_BROWSER_CONFIG, 'utf8'));
const credentials = JSON.parse(fs.readFileSync(config.credentials, 'utf8'));
const result = { status: 'RUNNING', cases: [], production_accessed: false };
const totp = seed => {
    let bits = '';
    for (const char of seed) bits += 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567'.indexOf(char).toString(2).padStart(5, '0');
    const key = Buffer.from(bits.match(/.{8}/g).map(byte => parseInt(byte, 2)));
    const counter = Buffer.alloc(8);
    counter.writeBigUInt64BE(BigInt(Math.floor(Date.now() / 30000)));
    const digest = crypto.createHmac('sha1', key).update(counter).digest();
    return String((digest.readUInt32BE(digest[19] & 15) & 0x7fffffff) % 1000000).padStart(6, '0');
};
let browser;
let phase = 'login';
(async () => {
    try {
        const args = ['--no-proxy-server'];
        if (config.port) args.push('--host-resolver-rules=MAP ' + new URL(config.url).hostname + ' 127.0.0.1:' + config.port);
        if (config.spki) args.push('--ignore-certificate-errors-spki-list=' + config.spki);
        phase = 'browser launch';
        browser = await chromium.launch({ executablePath: process.env.EMAILER_CHROMIUM_EXECUTABLE, headless: true, args });
        const context = await browser.newContext();
        const page = await context.newPage();
        phase = 'login GET';
        const loginResponse = await page.goto(config.url + '/login');
        result.loginStatus = loginResponse.status();
        phase = 'login fields';
        await page.locator('[name=login_identifier]').fill(credentials.email);
        await page.locator('[name=password]').fill(credentials.password);
        await page.getByRole('button', { name: 'Sign in', exact: true }).click();
        phase = 'login redirect';
        await page.waitForURL('**/admin');
        phase = 'MFA management after normal login';
        await page.goto(config.url + '/admin/mfa');
        assert.equal(new URL(page.url()).pathname, '/admin/mfa');
        result.cases.push({ name: phase, status: 'PASS' });
        phase = 'hold an old-session status poll';
        const pollPage = await context.newPage();
        await pollPage.goto(config.url + '/admin/mfa');
        let heldPoll, heldHeaders;
        await pollPage.route('**/admin/update-status?rotation-race=1', async route => { heldHeaders = await route.request().allHeaders(); heldPoll = route; });
        await pollPage.evaluate(() => { void fetch('/admin/update-status?rotation-race=1', { headers: { 'X-Requested-With': 'XMLHttpRequest' } }); });
        for (let attempt = 0; !heldPoll && attempt < 100; attempt++) await new Promise(resolve => setTimeout(resolve, 20));
        assert(heldPoll);
        phase = 'fresh authentication navigation';
        await page.goto(config.url + '/admin/reauthenticate?purpose=mfa_management');
        await page.locator('[name=password]').fill(credentials.password);
        await page.getByRole('button', { name: 'Confirm current credentials' }).click();
        await page.waitForLoadState('networkidle');
        // Record route only; never cookies, credentials, enrollment bodies or codes.
        result.returnPath = new URL(page.url()).pathname;
        phase = 'release revoked-session poll after rotation';
        const rotatedCookie = (await context.cookies()).find(cookie => cookie.name === 'EMAILERSESSID')?.value;
        const pollResponse = pollPage.waitForResponse(response => response.url().includes('rotation-race=1'));
        await heldPoll.continue({ headers: heldHeaders });
        await pollResponse;
        await pollPage.waitForTimeout(100);
        result.pollChangedCookie = rotatedCookie !== (await context.cookies()).find(cookie => cookie.name === 'EMAILERSESSID')?.value;
        phase = 'authenticated MFA GET after rotation';
        await page.goto(config.url + '/admin/mfa');
        result.afterRotationPath = new URL(page.url()).pathname;
        assert.equal(result.afterRotationPath, '/admin/mfa');
        result.cases.push({ name: phase, status: 'PASS' });
        assert.equal(result.returnPath, '/admin/mfa');
        phase = 'same-session enrollment through CSRF forms';
        await page.getByRole('button', { name: 'Start or restart enrollment' }).click();
        await page.getByRole('heading', { name: 'Save MFA recovery material' }).waitFor();
        const seed = await page.locator('p code').first().textContent();
        const recovery = await page.locator('li code').allTextContents();
        await page.locator('[name=totp_code]').fill(totp(seed));
        await page.locator('[name=recovery_saved]').check();
        await page.getByRole('button', { name: 'Confirm MFA', exact: true }).click();
        await page.waitForURL('**/admin/mfa');
        assert(await page.locator('main').getByText('Status: Enabled.', { exact: false }).isVisible());
        result.cases.push({ name: phase, status: 'PASS' });
        phase = 'existing MFA login and fresh management authentication';
        const existing = await browser.newContext();
        const signedIn = await existing.newPage();
        await signedIn.goto(config.url + '/login');
        await signedIn.locator('[name=login_identifier]').fill(credentials.email);
        await signedIn.locator('[name=password]').fill(credentials.password);
        await signedIn.locator('[name=mfa_code]').fill(recovery[0]);
        await signedIn.getByRole('button', { name: 'Sign in', exact: true }).click();
        await signedIn.waitForURL('**/admin');
        await signedIn.goto(config.url + '/admin/reauthenticate?purpose=mfa_management');
        await signedIn.locator('[name=password]').fill(credentials.password);
        await signedIn.locator('[name=mfa_code]').fill(recovery[1]);
        await signedIn.getByRole('button', { name: 'Confirm current credentials' }).click();
        await signedIn.waitForURL('**/admin/mfa');
        await signedIn.goto(config.url + '/admin/mfa');
        assert.equal(new URL(signedIn.url()).pathname, '/admin/mfa');
        result.cases.push({ name: phase, status: 'PASS' });
        result.status = 'PASS';
    } catch (error) {
        result.errorType = error.name;
        if (phase === 'browser launch') console.log(String(error.message).split('\n')[0]);
        if (error.name === 'Error' && String(error.message).includes('Executable doesn')) result.errorType = 'MissingBrowser';
        result.status = 'FAIL';
        result.failedPhase = phase;
        process.exitCode = 1;
    } finally {
        if (browser) await browser.close();
        fs.writeFileSync(path.join(config.output, 'mfa-browser-result.json'), JSON.stringify(result, null, 2) + '\n');
        console.log('MFA browser acceptance: ' + result.status + ' at ' + phase);
    }
})();
