const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {execFileSync} = require('node:child_process');
const {chromium} = require('playwright-core');
const config = JSON.parse(fs.readFileSync(process.env.EMAILER_BROWSER_CONFIG, 'utf8'));
const credentials = JSON.parse(fs.readFileSync(config.credentials, 'utf8'));
assert.match(config.maintenanceContainer, /^emailer-editor-[a-f0-9]{12}-web$/);
const fixture = action => execFileSync('docker', ['exec', config.maintenanceContainer, 'php', 'tools/browser/session-expiry-fixture.php', action], {encoding: 'utf8'});
const result = {status: 'FAIL', cases: []};
let browser, phase = 'launch';
(async () => {
    try {
        const args = ['--no-proxy-server', '--host-resolver-rules=MAP ' + new URL(config.url).hostname + ' 127.0.0.1:' + config.port, '--ignore-certificate-errors-spki-list=' + config.spki];
        browser = await chromium.launch({executablePath: process.env.EMAILER_CHROMIUM_EXECUTABLE, headless: true, args});
        const context = await browser.newContext();
        const editor = await context.newPage();
        const login = async page => {
            await page.locator('[name=login_identifier]').fill(credentials.email);
            await page.locator('[name=password]').fill(credentials.password);
            await page.getByRole('button', {name: 'Sign in', exact: true}).click();
            await page.waitForURL(url => url.pathname.startsWith('/admin'));
        };
        await editor.goto(config.url + '/login'); await login(editor);
        const id = JSON.parse(fixture('seed')).campaign;
        execFileSync('docker', ['exec', config.maintenanceContainer, 'php', 'tools/browser/verify-editor-delivery.php', 'snapshot']);
        phase = 'retain unsaved campaign and selected file';
        await editor.goto(config.url + '/admin/campaigns/' + id + '/edit');
        phase = 'campaign enhancement';
        await editor.locator('[data-campaign-enhanced=true]').waitFor();
        phase = 'campaign fields and CSV';
        await editor.locator('[name=name]').fill('Unsaved recovery name');
        const csv = 'email\nretained@example.test\n';
        await editor.locator('[name=recipient_csv]').setInputFiles({name: 'retained.csv', mimeType: 'text/csv', buffer: Buffer.from(csv)});
        const summary = await context.newPage();
        await summary.goto(config.url + '/admin/campaigns/' + id);
        phase = 'real idle expiry in both pollers';
        fixture('idle');
        const notice = editor.locator('[data-authentication-expired]');
        await summary.bringToFront();
        phase = 'progress poll idle notice';
        await summary.locator('[data-authentication-expired]').waitFor({timeout: 40000});
        await editor.bringToFront();
        phase = 'update poll idle notice';
        await notice.waitFor({timeout: 40000});
        assert.match(await notice.innerText(), /You’ve been signed out due to inactivity\. Sign in again to continue\./);
        assert.doesNotMatch(await editor.locator('body').innerText(), /Current update state is unavailable|Sending is disabled until/);
        assert.doesNotMatch(await summary.locator('[data-progress-feedback]').innerText(), /Live update unavailable/);
        result.cases.push('Idle notice in update and progress polls without delivery diagnosis');
        phase = 'login continuation and unchanged live editor';
        const popupPromise = context.waitForEvent('page');
        await notice.getByRole('link', {name: 'Sign in again'}).click();
        const popup = await popupPromise; await popup.waitForLoadState();
        assert.match(await popup.locator('main').innerText(), /signed out due to inactivity/);
        phase = 'login submit and intended continuation';
        await login(popup);
        phase = 'unchanged fields and security refresh';
        assert.equal(new URL(popup.url()).pathname, '/admin/campaigns/' + id + '/edit');
        assert.equal(await editor.locator('[name=name]').inputValue(), 'Unsaved recovery name');
        assert.equal(await editor.locator('[name=recipient_csv]').evaluate(async input => input.files[0].text()), csv);
        await editor.locator('[data-campaign-refresh-security]').click();
        await editor.getByText('Security check refreshed.', {exact: false}).waitFor();
        result.cases.push('Sign-in returns to intended editor; original unsaved fields CSV and security refresh survive');
        phase = 'absolute expiry has a distinct explanation';
        fixture('absolute');
        const absolute = await popup.evaluate(async () => {
            const response = await fetch('/admin/update-status', {headers: {'X-Requested-With': 'XMLHttpRequest', Accept: 'application/json'}});
            return {status: response.status, body: await response.json()};
        });
        assert.equal(absolute.status, 401); assert.equal(absolute.body.expiry, 'absolute');
        await popup.goto(config.url + absolute.body.login_url);
        assert.match(await popup.locator('main').innerText(), /session reached its 12-hour limit/);
        assert.doesNotMatch(await popup.locator('main').innerText(), /due to inactivity/);
        result.cases.push('Absolute lifetime expiry is identified accurately');
        phase = 'legacy redirect HTML recognition';
        await editor.route('**/admin/update-status', route => route.fulfill({status: 302, headers: {location: '/login?expiry=idle'}}));
        await editor.bringToFront();
        await editor.locator('[data-authentication-expired]').filter({hasText: 'due to inactivity'}).waitFor({timeout: 40000});
        assert.doesNotMatch(await editor.locator('body').innerText(), /Current update state is unavailable/);
        result.cases.push('Legacy 302 followed by HTML is an authentication event');
        result.status = 'PASS';
    } catch (error) {
        result.errorType = error.name;
        if (!phase.includes('login')) result.errorSummary = String(error.message).split('\n')[0].slice(0, 140);
        result.failedPhase = phase;
        process.exitCode = 1;
    } finally {
        fs.writeFileSync(path.join(config.output, 'session-expiry-result.json'), JSON.stringify(result, null, 2), {mode: 0o600});
        if (browser) await browser.close();
        console.log(JSON.stringify(result));
    }
})();
